void Maze::draw()
{
    // ----------------------------
    // Floor (Texture Repeat 30x30)
    // ----------------------------
    glBindTexture(GL_TEXTURE_2D, g_floorTex);
    glColor3f(1, 1, 1);

    glBegin(GL_QUADS);
    glNormal3f(0, 1, 0);

    glTexCoord2f(0, 0);          glVertex3f(-15, 0, -15);
    glTexCoord2f(30, 0);         glVertex3f(15, 0, -15);
    glTexCoord2f(30, 30);        glVertex3f(15, 0, 15);
    glTexCoord2f(0, 30);         glVertex3f(-15, 0, 15);

    glEnd();


    // ----------------------------
    // Walls — one quad per face
    // ----------------------------
    glBindTexture(GL_TEXTURE_2D, g_wallTex);

    for (int z = 0; z < 30; z++)
    {
        for (int x = 0; x < 30; x++)
        {
            if (map[z][x] != 1) continue;

            float cx = x - 15 + 0.5f;
            float cz = z - 15 + 0.5f;
            float w = 0.5f;
            float h = 2.0f;

            glBegin(GL_QUADS);
            glColor3f(1, 1, 1);

            // ---------------- FRONT ----------------
            glNormal3f(0, 0, -1);
            glTexCoord2f(0, 0); glVertex3f(cx - w, 0, cz - w);
            glTexCoord2f(1, 0); glVertex3f(cx + w, 0, cz - w);
            glTexCoord2f(1, 1); glVertex3f(cx + w, h, cz - w);
            glTexCoord2f(0, 1); glVertex3f(cx - w, h, cz - w);

            // ---------------- BACK ----------------
            glNormal3f(0, 0, 1);
            glTexCoord2f(0, 0); glVertex3f(cx - w, 0, cz + w);
            glTexCoord2f(1, 0); glVertex3f(cx + w, 0, cz + w);
            glTexCoord2f(1, 1); glVertex3f(cx + w, h, cz + w);
            glTexCoord2f(0, 1); glVertex3f(cx - w, h, cz + w);

            // ---------------- LEFT ----------------
            glNormal3f(-1, 0, 0);
            glTexCoord2f(0, 0); glVertex3f(cx - w, 0, cz - w);
            glTexCoord2f(1, 0); glVertex3f(cx - w, 0, cz + w);
            glTexCoord2f(1, 1); glVertex3f(cx - w, h, cz + w);
            glTexCoord2f(0, 1); glVertex3f(cx - w, h, cz - w);

            // ---------------- RIGHT ----------------
            glNormal3f(1, 0, 0);
            glTexCoord2f(0, 0); glVertex3f(cx + w, 0, cz - w);
            glTexCoord2f(1, 0); glVertex3f(cx + w, 0, cz + w);
            glTexCoord2f(1, 1); glVertex3f(cx + w, h, cz + w);
            glTexCoord2f(0, 1); glVertex3f(cx + w, h, cz - w);

            glEnd();
        }
    }
}

bool Maze::checkCollision(float px, float pz, float radius)
{
    int tx = int(px + 15);
    int tz = int(pz + 15);

    if (tx < 0 || tx >= 30 || tz < 0 || tz >= 30)
        return true;

    return (map[tz][tx] == 1);
}
